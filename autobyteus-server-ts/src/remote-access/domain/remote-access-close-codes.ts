import type { RemoteAccessAuthFailureCode } from "./models.js";

/** How a Remote Access refusal closes a WebSocket: the close code for each failure code. */
export const REMOTE_ACCESS_CLOSE_CODE_BY_FAILURE: Readonly<Record<RemoteAccessAuthFailureCode, number>> = Object.freeze({
  REMOTE_ACCESS_AUTH_REQUIRED: 4401,
  REMOTE_ACCESS_AUTH_INVALID: 4401,
  REMOTE_ACCESS_DEVICE_REVOKED: 4403,
  PHONE_ACCESS_DISABLED: 4403,
  REMOTE_ACCESS_ROUTE_UNSUPPORTED: 4404,
  REMOTE_ACCESS_LOCAL_ONLY: 4403,
  REMOTE_ACCESS_PAIRING_EXPIRED: 4401,
  REMOTE_ACCESS_PAIRING_INVALID: 4401,
  REMOTE_ACCESS_PAIRING_CONSUMED: 4401,
  REMOTE_ACCESS_PAIRING_URL_INVALID: 4403,
  REMOTE_ACCESS_PAIRING_URL_LOCAL_ONLY: 4403,
  REMOTE_ACCESS_PAIRING_HTTP_PRIVATE_REQUIRED: 4403,
  REMOTE_ACCESS_PAIRING_HTTP_ACK_REQUIRED: 4403,
  REMOTE_ACCESS_PAIRING_WAY_INVALID: 4403,
  REMOTE_ACCESS_NETWORK_ID_INVALID: 4403,
  REMOTE_ACCESS_ORIGIN_REFUSED: 4403,
  REMOTE_ACCESS_HOST_REFUSED: 4403,
  PHONE_ACCESS_ROUTE_REFUSED: 4403,
});

export type RemoteAccessWebSocketClose = Readonly<{ code: number; reason: RemoteAccessAuthFailureCode }>;

export const remoteAccessCloseForFailure = (failure: RemoteAccessAuthFailureCode): RemoteAccessWebSocketClose => ({
  code: REMOTE_ACCESS_CLOSE_CODE_BY_FAILURE[failure],
  reason: failure,
});
