#!/usr/bin/env python3
"""Build in a disposable Ubuntu24.04 container/VM with authenticated deb-src enabled.
No engine install, mount, publish or root command. Output only the exact runtime
pair, corresponding modified source, notices and measured provenance. See README.
"""
import argparse
import gzip
import json
import os
import shutil
import subprocess
import tarfile
from pathlib import Path
from source import HERE, LOCK, VERSION, NAMES, identity, prepare, run, source_identity


def build(work, output, base):
    if subprocess.check_output(['lsb_release', '-rs'], text=True).strip() != '24.04':
        raise ValueError('The source recipe requires Ubuntu24.04')
    arch = subprocess.check_output(['dpkg', '--print-architecture'], text=True).strip()
    if arch not in ('amd64', 'arm64'):
        raise ValueError('Unsupported engine architecture')
    tree = prepare(work)
    output.mkdir(parents=True, exist_ok=False)
    # Keep the distro source packaging/rules and entire original tarball. No
    # custom minimal FSAL build or autogenerated quilt attribution is substituted.
    run('dpkg-source', '-b', '.', cwd=tree)
    corresponding = work / 'corresponding-source'
    corresponding.mkdir()
    shutil.copytree(HERE, corresponding / 'recipe', ignore=shutil.ignore_patterns('__pycache__'))
    for pattern in (f'nfs-ganesha_{VERSION}.dsc', f'nfs-ganesha_{VERSION}.debian.tar.*',
                    'nfs-ganesha_4.3.orig.tar.gz'):
        matches = list(work.glob(pattern))
        if len(matches) != 1:
            raise ValueError('Missing corresponding source component '+pattern)
        shutil.copyfile(matches[0], corresponding / matches[0].name)
    shutil.copyfile(tree/'debian/copyright', corresponding/'COPYRIGHT')
    archive = output / f'autobyteus-nfs-ganesha-source-{VERSION}-{arch}.tar.gz'
    with archive.open('wb') as f, gzip.GzipFile(fileobj=f, mode='wb', mtime=LOCK['sourceDateEpoch'], filename='') as gz:
        with tarfile.open(fileobj=gz, mode='w') as tar:
            for path in sorted(corresponding.rglob('*')):
                if path.is_file():
                    info = tar.gettarinfo(str(path), arcname=str(path.relative_to(corresponding)))
                    info.mtime = LOCK['sourceDateEpoch']; info.uid = info.gid = 0
                    info.uname = info.gname = ''; info.mode = 0o644
                    with path.open('rb') as data:
                        tar.addfile(info, data)
    run('dpkg-buildpackage', '-b', '-us', '-uc', '-j4', cwd=tree)
    packages = []
    for name in NAMES:
        path = work / f'{name}_{VERSION}_{arch}.deb'
        fields = subprocess.check_output(['dpkg-deb', '-f', str(path), 'Package', 'Version', 'Architecture'], text=True)
        expected = f'Package: {name}\nVersion: {VERSION}\nArchitecture: {arch}\n'
        if fields != expected or not 0 < path.stat().st_size <= 40*1024*1024:
            raise ValueError('Built engine package identity/size mismatch')
        shutil.copyfile(path, output/path.name)
        packages.append(identity(path) | {'name': name, 'version': VERSION, 'architecture': arch})
    inventory = output / f'engine-build-{arch}.txt'
    inventory.write_text('Build base: '+base+'\nSOURCE_DATE_EPOCH='+str(LOCK['sourceDateEpoch'])+'\n'+
                         subprocess.check_output(['uname', '-a'], text=True)+
                         subprocess.check_output(['dpkg-query', '-W', '-f=${Package} ${Version} ${Architecture}\n'], text=True))
    # Debian buildinfo records exact installed build dependencies/toolchain.
    for p in work.glob('*.buildinfo'):
        with inventory.open('a') as f:
            f.write('\n'+p.read_text())
    shutil.copyfile(tree/'debian/copyright', output/'COPYRIGHT')
    manifest = {'source': source_identity(base), 'architectures': {arch: {
        'packages': packages, 'correspondingSource': identity(archive), 'buildInventory': identity(inventory)}}}
    (output/'engine-manifest.json').write_text(json.dumps(manifest, indent=2)+'\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--work', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--base', required=True, help='Pinned actual build-container/image identity')
    args = parser.parse_args()
    build(args.work.resolve(), args.output.resolve(), args.base)
