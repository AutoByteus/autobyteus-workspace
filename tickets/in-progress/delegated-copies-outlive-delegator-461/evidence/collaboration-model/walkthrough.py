"""Generates the contract's §5.1 … §5.3 from the model: every state after every call, file by file.
  python3 -I walkthrough.py                 prints the generated markdown
  python3 -I walkthrough.py --write FILE    replaces the generated part of the contract FILE
  python3 -I walkthrough.py --check FILE    exits 1 when the contract's generated part differs from the model"""
import copy, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # model.py and stories.py sit beside this file
from model import Refused
from stories import STORIES

BEGIN = "<!-- generated by evidence/collaboration-model/walkthrough.py: do not edit by hand -->"
END = "<!-- end of generated part -->"

def fmt(v, indent=0, width=118):
    one = json.dumps(v, ensure_ascii=False)
    if len(one) + indent <= width or not isinstance(v, (dict, list)) or not v: return one
    pad = " " * (indent + 2)
    if isinstance(v, dict):
        items = [f'{pad}{json.dumps(k, ensure_ascii=False)}: {fmt(x, indent + 2, width)}' for k, x in v.items()]
        return "{\n" + ",\n".join(items) + "\n" + " " * indent + "}"
    items = [pad + fmt(x, indent + 2, width) for x in v]
    return "[\n" + ",\n".join(items) + "\n" + " " * indent + "]"

def show(path, two_nodes):
    node, p = path.split(":", 1)
    p = f"`{p[:-len(' (memory)')]}` (memory folder)" if p.endswith(" (memory)") else f"`{p}`"
    return f"node {node}: {p}" if two_nodes else p

ROWKEY = ("runId", "teamRunId", "orgRunId")
def rowkey(r): return next(r[k] for k in ROWKEY if k in r)

def diff(before, after, two_nodes):
    out, unchanged = [], []
    for path in sorted(set(before) | set(after)):
        b, a = before.get(path), after.get(path)
        label = show(path, two_nodes)
        if b == a:
            if b is not None: unchanged.append(label)
            continue
        if a is None: out.append(f"**Removed:** {label}"); continue
        if a == "created": out.append(f"**Created:** {label}: the agent's own memory; its first input is kept there"); continue
        if path.endswith("_index.json"):
            old = {rowkey(r): r for r in (b or [])}
            for r in a:
                if old.get(rowkey(r)) != r:
                    kind = "new row" if rowkey(r) not in old else "changed row"
                    out.append(f"**{'Created' if kind == 'new row' else 'Changed'}:** {label}, {kind}:\n```json\n{fmt(r)}\n```")
            continue
        if path.endswith(".jsonl"):
            new = a[len(b or []):]
            verb = "Created" if b is None else "Changed"
            out.append(f"**{verb}:** {label}, {'its first line' if b is None and len(new) == 1 else 'new line' if len(new) == 1 else 'new lines'}:\n"
                       + "\n".join(f"```json\n{fmt(x)}\n```" for x in new))
            continue
        out.append(f"**{'Created' if b is None else 'Changed'}:** {label}:\n```json\n{fmt(a)}\n```")
    return out, unchanged

WALK = "collaboration-walkthrough.md"
def render_index():
    md = [BEGIN, "", f"Every state below is in [`{WALK}`]({WALK}), with every file after every call in full. That file and this list are generated from the contract's executable model (`evidence/collaboration-model/`: `model.py` holds the rules, `stories.py` the stories); `walkthrough.py --check` confirms that both match the model.", ""]
    for num, title, story in STORIES:
        w, steps = story()
        md += [f"### {num} {title}", "", "| State | Step | Case IDs |", "| --- | --- | --- |"]
        md += [f"| {s['id']} | {s['title']} | {s['cases']} |" for s in steps] + [""]
    md += [END]
    return "\n".join(md)

def render():
    md = ["# Collaboration Walkthrough — Every State, File By File", "",
          "Generated by `evidence/collaboration-model/walkthrough.py` from the executable model of `target-collaboration-contract.md`. Do not edit by hand: change the contract's rules in `model.py` or the stories in `stories.py`, and generate again.", "",
          "Each state gives the call exactly as the agent writes it, the result, how the call is found and admitted, then every file that is created, changed or removed, in full (a run list or a message log shows its new or changed rows), the files that do not change, and the in-memory `DelegationIndex` when it changes. The case IDs are the contract's (§5.4).", ""]
    for num, title, story in STORIES:
        w, steps = story()
        two_nodes = num == "5.1"
        md += [f"### {num} {title}", "", "**The steps:**", "", "| State | Step | Case IDs |", "| --- | --- | --- |"]
        md += [f"| {s['id']} | {s['title']} | {s['cases']} |" for s in steps]
        md += [""]
        for s in steps:
            before = copy.deepcopy(w.disk); trees_before = {n: w.tree(n) for n in ("A", "B")}
            w.result, w.receiver_sees = None, None
            results, seen = [], []
            orig = w._deliver
            def deliver(*a, **k):
                orig(*a, **k); results.append(w.result); seen.append(w.receiver_sees)
            w._deliver = deliver
            try:
                s["op"](); refused = None
            except Refused as r:
                refused = r
            w._deliver = orig
            if w.result is not None and w.result not in results: results.append(w.result)
            changes, unchanged = diff(before, w.disk, two_nodes)
            md += ["---", "", f"#### {s['id']} — {s['title']} [{s['cases']}]", "", f"**Call:** {s['call']}", ""]
            for r in results: md += [f"**Result to the caller:** `{json.dumps(r, ensure_ascii=False)}`", ""]
            if refused and refused.tool == "delegate_task":
                md += [f"**Result:** refused, `{{ \"delegated\": false, \"message\": {json.dumps(refused.message)} }}`", ""]
            elif refused: md += [f"**Result:** refused, `{{ \"accepted\": false, \"code\": \"{refused.code}\", \"message\": {json.dumps(refused.message)} }}`", ""]
            md += [f"**How:** {s['found']}", ""]
            for x in seen: md += [f"**The receiver sees:** `{x}`", ""]
            if changes: md += ["**On disk after this step:**", ""] + sum(([c, ""] for c in changes), [])
            else: md += ["**On disk after this step:** nothing changes.", ""]
            if unchanged and changes: md += [f"**Unchanged:** " + ", ".join(unchanged) + ".", ""]
            for n in ("A", "B") if two_nodes else ("A",):
                t = w.tree(n)
                if t != trees_before[n]:
                    md += [f"**In memory{' on node ' + n if two_nodes else ''} (the `DelegationIndex`):**", "```json", fmt(t), "```", ""]
            if all(w.tree(n) == trees_before[n] for n in ("A", "B")) and s["id"] not in ("S0", "U0", "O0"):
                md += ["**In memory:** unchanged.", ""]
            md += [f"**Against today:** {s['today']}", "", f"**Checked on the user's data:** {s['checked']}", ""]
    return "\n".join(md) + "\n"

if __name__ == "__main__":
    if len(sys.argv) == 1: print(render()); sys.exit(0)
    mode, path = sys.argv[1], sys.argv[2]
    walk_path = os.path.join(os.path.dirname(os.path.abspath(path)), WALK)
    out = render_index()
    text = open(path, encoding="utf-8").read()
    i, j = text.find(BEGIN), text.find(END)
    def examples_in_model():
        """Every JSON example of the contract's §3 … §4 must be a state the model produces ("…" matches anything)."""
        import re
        def objs(t):
            out = []
            for blk in re.findall(r"```json\n(.*?)```", t, re.S):
                try: v = json.loads(blk)
                except Exception: continue
                out += v if isinstance(v, list) else [v]
            return out
        def match(x, y):
            if x == "…" or x == {"…": "…"}: return True
            if isinstance(x, dict) and isinstance(y, dict):
                return all(k == "…" or (k in y and match(v, y[k])) for k, v in x.items())
            if isinstance(x, list) and isinstance(y, list): return len(x) == len(y) and all(match(a, b) for a, b in zip(x, y))
            return x == y
        body = text[text.index("## 3. On disk"):text.index("## 5. Every case")]
        def every(v):
            if isinstance(v, dict):
                yield v
                for x in v.values(): yield from every(x)
            elif isinstance(v, list):
                for x in v: yield from every(x)
        states = [d for o in objs(render()) for d in every(o)]  # a file, or any record inside one (a Task entry)
        bad = [x for x in objs(body) if not any(match(x, y) for y in states)]
        for x in bad: print("NOT A MODEL STATE:", json.dumps(x)[:160])
        return not bad
    if mode == "--check":
        ok_examples = examples_in_model()
        print("the contract's §3 … §4 examples are states of the model" if ok_examples else "MISMATCH: some §3 … §4 examples are not states of the model")
        ok = i >= 0 and text[i:j + len(END)] == out
        ok_walk = os.path.exists(walk_path) and open(walk_path, encoding="utf-8").read() == render()
        print("the contract's §5.1 … §5.3 match the model" if ok else "MISMATCH: the contract's §5.1 … §5.3 differ from the model")
        print(f"{WALK} matches the model" if ok_walk else f"MISMATCH: {WALK} differs from the model")
        sys.exit(0 if ok and ok_walk and ok_examples else 1)
    if mode == "--write":
        open(walk_path, "w", encoding="utf-8").write(render())
        if i < 0:
            a = text.index("### 5.1 You start a standalone agent"); b = text.index("### 5.4 Reference for every run")
            text = text[:a] + out + "\n\n---\n\n" + text[b:]
        else:
            text = text[:i] + out + text[j + len(END):]
        open(path, "w", encoding="utf-8").write(text); print("written")
