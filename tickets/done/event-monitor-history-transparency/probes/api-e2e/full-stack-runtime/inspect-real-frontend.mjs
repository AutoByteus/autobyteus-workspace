import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
const outputDir = new URL('.', import.meta.url).pathname;
const require = createRequire(new URL('../../../../../../autobyteus-web/package.json', import.meta.url));
const { chromium } = require('playwright-core');
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const context=await browser.newContext({viewport:{width:1280,height:900}});
const page=await context.newPage();
const logs=[], errors=[], failed=[];
page.on('console',m=>logs.push({type:m.type(),text:m.text()}));
page.on('pageerror',e=>errors.push(String(e)));
page.on('requestfailed',r=>failed.push({url:r.url(),error:r.failure()?.errorText}));
await page.goto('http://127.0.0.1:54588/',{waitUntil:'domcontentloaded',timeout:90000});
await page.waitForTimeout(12000);
await page.screenshot({path:path.join(outputDir,'real-frontend-after-warmup.png'),fullPage:true});
const info=await page.evaluate(()=>({url:location.href,title:document.title,readyState:document.readyState,bodyText:document.body?.innerText??'',bodyHtml:document.body?.innerHTML.slice(0,10000)??'',buttons:[...document.querySelectorAll('button')].map((b,i)=>({i,text:b.innerText,aria:b.getAttribute('aria-label'),title:b.getAttribute('title')})),links:[...document.querySelectorAll('a')].map((a,i)=>({i,text:a.innerText,href:a.getAttribute('href')}))}));
await fs.writeFile(path.join(outputDir,'real-frontend-inspection.json'),JSON.stringify({info,logs,errors,failed},null,2)+'\n');
console.log(JSON.stringify({url:info.url,title:info.title,bodyText:info.bodyText.slice(0,5000),buttons:info.buttons,links:info.links,logs:logs.slice(-20),errors,failed},null,2));
await browser.close();
