const out = process.argv[2]
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto('http://127.0.0.1:3000/workspace', { waitUntil: 'networkidle' })
await page.waitForSelector('[data-test="run-section-switch"]')
await page.waitForTimeout(800)
await page.setViewportSize({ width: 600, height: 800 }); await page.waitForTimeout(800)
console.log('strip label (workspaces):', await page.getAttribute('[data-nav-key="workspaces"]', 'aria-label'))
await page.setViewportSize({ width: 1440, height: 900 }); await page.waitForTimeout(800)
await page.click('[data-test="run-section-tab-projects"]')
await page.setViewportSize({ width: 600, height: 800 }); await page.waitForTimeout(800)
console.log('strip label (projects):', await page.getAttribute('[data-nav-key="workspaces"]', 'aria-label'))
await page.screenshot({ path: `${out}/IMP-09-16-narrow-strip-projects-mode.png` })
await page.evaluate(() => { localStorage.setItem('autobyteus.localization.preference-mode', 'zh-CN') })
await page.setViewportSize({ width: 1440, height: 900 })
await page.reload({ waitUntil: 'networkidle' })
await page.waitForSelector('[data-test="project-row"]', { timeout: 30000 })
await page.click('[data-test="project-row"] >> nth=1 >> [data-test="project-row-select"]')
await page.waitForTimeout(600)
console.log('zh tabs:', await page.$$eval('[data-test="run-section-switch"] [role="tab"]', (els) => els.map((e) => e.textContent.trim())))
console.log('zh header +:', await page.getAttribute('[data-test="run-section-new-project"]', 'aria-label'))
console.log('zh no-runs:', await page.textContent('[data-test="project-no-runs"]'))
await page.screenshot({ path: `${out}/IMP-09-15-projects-mode-zh-CN.png` })
