import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const [serverDir, root] = process.argv.slice(2);
const req = createRequire(serverDir + '/package.json');
const reg = await import(pathToFileURL(req.resolve('autobyteus-ts/tools/registry/tool-registry.js')).href);
const cfg = await import(pathToFileURL(serverDir + '/dist/config/app-config-provider.js').href);
const nat = await import(pathToFileURL(serverDir + '/dist/agent-tools/project-tasks/project-task-native-tools.js').href);
cfg.appConfigProvider.initialize({ appDataDir: root });
nat.registerProjectTaskTools();
const names = (reg.defaultToolRegistry.listToolNames?.() ?? []).filter((n) => /task|project/.test(n));
console.log('registered:', JSON.stringify(names));
console.log('old name present:', Boolean(reg.defaultToolRegistry.getToolDefinition('create_or_update_task')));
const call = async (n, a) => JSON.parse(await reg.defaultToolRegistry.createTool(n).execute(null, a));
const proj = await call('create_or_update_project', { name: 'ttsplit probe' });
console.log('project', JSON.stringify(proj));
const projectId = proj.project_id ?? proj.projectId ?? proj.project?.projectId;
const created = await call('create_task', { project_id: projectId, description: 'native create' });
console.log('create_task', JSON.stringify(created));
const taskId = created.task_id ?? created.taskId ?? created.task?.taskId;
const updated = await call('update_task', { task_id: taskId, status: 'DONE' });
console.log('update_task DONE', JSON.stringify(updated));
const bad = await call('create_task', { description: 'no project' }).catch(e => ({ thrown: String(e) }));
console.log('create_task missing project_id', JSON.stringify(bad));
const bad2 = await call('update_task', { description: 'no id' }).catch(e => ({ thrown: String(e) }));
console.log('update_task missing task_id', JSON.stringify(bad2));
