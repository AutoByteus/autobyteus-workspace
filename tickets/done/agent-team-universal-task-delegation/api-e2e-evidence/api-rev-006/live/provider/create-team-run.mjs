import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
const [fixturePath, runtimeKind, model, outputPath] = process.argv.slice(2);
if (!fixturePath || !runtimeKind || !model || !outputPath) throw new Error('usage');
const f=JSON.parse(await readFile(fixturePath,'utf8'));
const graphqlUrl=process.env.GRAPHQL_URL ?? 'http://127.0.0.1:60311/graphql';
const gql=async(query,variables={})=>{const r=await fetch(graphqlUrl,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({query,variables})});const j=await r.json();if(!r.ok||j.errors?.length) throw new Error(JSON.stringify(j.errors??j));return j.data;};
await mkdir(f.workspaceRoot,{recursive:true});
const members=[['/coordinator',f.coordinator.id],['/worker',f.worker.id],['/lab/lead',f.nestedCoordinator.id],['/lab/researcher',f.nestedWorker.id]];
const request={teamDefinitionId:f.rootTeam.id,memberConfigs:members.map(([memberAddress,agentDefinitionId])=>({memberAddress,agentDefinitionId,llmModelIdentifier:model,autoExecuteTools:true,skillAccessMode:'NONE',workspaceRootPath:f.workspaceRoot,runtimeKind}))};
const response=await gql(`mutation($input:CreateAgentTeamRunInput!){createAgentTeamRun(input:$input){success message teamRunId}}`,{input:request});
const teamRunId=response.createAgentTeamRun.teamRunId;
const resume=await gql(`query($id:String!){getTeamRunResumeConfig(teamRunId:$id){teamRunId isActive executionTree}}`,{id:teamRunId});
const root=resume.getTeamRunResumeConfig.executionTree.root_team;
const coordinator=root.members.find((m)=>m.address==='/coordinator');
if(!coordinator?.agent_run_id) throw new Error('missing coordinator AgentRun');
const result={request,response:{data:response},resume:{data:resume},teamRunId,coordinatorAgentRunId:coordinator.agent_run_id};
await writeFile(outputPath,JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify({teamRunId,coordinatorAgentRunId:coordinator.agent_run_id},null,2));
