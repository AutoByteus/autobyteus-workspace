import playwright from '../../../../../../autobyteus-web/node_modules/playwright-core/index.js';
import fs from 'node:fs/promises';
const b=await playwright.chromium.connectOverCDP('http://127.0.0.1:9222');
const p=b.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('127.0.0.1:3589'));
const out=new URL('./',import.meta.url);const ev=[];
const snap=async label=>p.evaluate(label=>({label,at:new Date().toISOString(),url:location.href,head:[...document.querySelectorAll('h1,h2,h3,[data-test="workspace-header-title"],[data-test="workspace-header-name"]')].map(e=>e.textContent?.replace(/\s+/g,' ').trim()),selected:[...document.querySelectorAll('[aria-current="true"],[data-test^="workspace-team-member-"][aria-selected="true"],[data-test^="agent-org-"][aria-selected="true"]')].map(e=>({test:e.getAttribute('data-test'),text:e.textContent?.replace(/\s+/g,' ').trim(),selected:e.getAttribute('aria-selected'),current:e.getAttribute('aria-current')})),body:document.body.innerText}),label);
const team=p.locator('[data-test^="workspace-team-member-"][data-test$="-/aorg_e2e_analyst"]');
const org=p.locator('[data-test^="agent-org-agent-row-aorg_e2e_concierge"]');
ev.push(await snap('active-org-before'));
await team.click();
await p.waitForFunction(()=>location.search==='' && document.body.innerText.includes('aorg_e2e_analyst'),null,{timeout:15000});
ev.push(await snap('inactive-team-after'));
await p.screenshot({path:new URL('screenshots/LIVE-001-active-org-to-inactive-team.png',out).pathname,fullPage:true});
await org.click();
await p.waitForFunction(()=>new URL(location.href).searchParams.get('rootSubjectKind')==='agent_org'&&document.body.innerText.includes('aorg e2e concierge -'),null,{timeout:15000});
ev.push(await snap('active-org-return'));
await fs.writeFile(new URL('LIVE-001-active-org-to-inactive-team.json',out),JSON.stringify(ev,null,2));
console.log(JSON.stringify(ev.map(x=>({label:x.label,url:x.url,selected:x.selected,head:x.head})),null,2));
await b.close();
